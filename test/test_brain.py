"""
End-to-end tests for the second brain. Each hook runs as a subprocess with a
throwaway DUPE_GUARD_HOME and vault; transcripts are synthetic JSONL in the
shape Claude Code writes. distill talks to a fake `claude` that replies from
files, so the hard cases (EMPTY, bad format, split votes) are reproducible
and cost nothing.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRAIN = ROOT / "brain"

FAKE_CLAUDE = textwrap.dedent('''\
    #!/usr/bin/env python3
    import os, sys
    prompt = sys.stdin.read()
    d = os.environ["FAKE_DIR"]
    kind = "stale" if "does the new block make" in prompt else "distill"
    n = 0
    while True:                       # atomic call counter, safe in parallel
        try:
            os.mkdir(os.path.join(d, f"{kind}-call-{n}")); break
        except FileExistsError:
            n += 1
    f = os.path.join(d, f"{kind}-{n}.txt")
    if not os.path.exists(f):
        f = os.path.join(d, f"{kind}-default.txt")
    print(open(f).read() if os.path.exists(f) else "EMPTY")
''')

NOTE = """---
tags: [project]
---

# billing-api

## Architecture

Invoices are generated by a nightly job and stored in Postgres.

## Decisions

- Retries use exponential backoff.

## Related

- [[Payments]]
"""


def line(**kw):
    # compact, the way Claude Code writes its transcripts
    return json.dumps(kw, separators=(",", ":")) + "\n"


def transcript(path, cwd, prompts, sid="s1", extra=()):
    """A synthetic transcript: prompts, assistant replies, an Edit, usage."""
    rows = [line(type="ai-title", aiTitle="Invoice retries")]
    t = 0
    for p in prompts:
        t += 1
        rows.append(line(type="user", cwd=cwd, gitBranch="feature/x", sessionId=sid,
                         timestamp=f"2026-09-20T10:{t:02d}:00Z", message={"role": "user", "content": p}))
        rows.append(line(type="assistant", cwd=cwd, timestamp=f"2026-09-20T10:{t:02d}:30Z",
                         message={"role": "assistant", "usage": {"input_tokens": 10, "output_tokens": 5},
                                  "content": [{"type": "text", "text": "Decided to keep the nightly job because "
                                               "moving invoices to a queue would double the failure modes. " * 2},
                                              {"type": "tool_use", "id": f"t{t}", "name": "Edit",
                                               "input": {"file_path": f"{cwd}/src/invoice.py"}}]}))
    rows.extend(extra)
    Path(path).write_text("".join(rows))


class BrainCase(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="dupe-guard-brain-"))
        self.home = self.tmp / "home"
        self.vault = self.tmp / "vault"
        self.repo = self.tmp / "billing-api"
        (self.vault / "Projects").mkdir(parents=True)
        (self.vault / "Projects" / "billing-api.md").write_text(NOTE)
        (self.vault / "Concepts").mkdir()
        (self.vault / "Concepts" / "Exponential backoff.md").write_text(
            "# Exponential backoff\n\nRetry delays double each attempt, with jitter, capped at a maximum.\n")
        (self.repo / "src").mkdir(parents=True)
        (self.repo / "src" / "invoice.py").write_text("def total(): return 1\n")
        subprocess.run(["git", "init", "-q"], cwd=self.repo, check=True)
        self.fake = self.tmp / "fake"
        self.fake.mkdir()
        (self.fake / "claude").write_text(FAKE_CLAUDE)
        (self.fake / "claude").chmod(0o755)
        # Never the developer's real transcripts: an index built from them made
        # these tests pass locally and fail on CI, where there are none.
        (self.tmp / "transcripts").mkdir()
        self.env = {**os.environ, "DUPE_GUARD_HOME": str(self.home), "DUPE_GUARD_VAULT": str(self.vault),
                    "DUPE_GUARD_TRANSCRIPTS": str(self.tmp / "transcripts"),
                    "DUPE_GUARD_BRAIN": "1", "DUPE_GUARD_CLAUDE": str(self.fake / "claude"),
                    "FAKE_DIR": str(self.fake)}

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def run_py(self, script, payload=None, env=None, args=()):
        r = subprocess.run([sys.executable, str(BRAIN / script), *args],
                           input=json.dumps(payload) if payload is not None else "",
                           capture_output=True, text=True, timeout=60, env=env or self.env)
        self.assertEqual(r.returncode, 0, r.stderr + r.stdout)
        return r.stdout

    def context(self, out):
        return json.loads(out)["hookSpecificOutput"]["additionalContext"] if out.strip() else None

    def end_session(self, prompts, sid="s1", extra=()):
        tp = self.tmp / f"{sid}.jsonl"
        transcript(tp, str(self.repo), prompts, sid, extra)
        self.run_py("session_log.py", {"session_id": sid, "transcript_path": str(tp), "reason": "exit"})
        return tp

    def raw_today(self):
        files = list((self.vault / "Sessions" / "Raw").glob("*.md"))
        return files[0].read_text() if files else ""

    def reply(self, kind, n, text):
        (self.fake / f"{kind}-{n}.txt").write_text(text)

    def queue_one(self):
        self.end_session(["make invoice retries use exponential backoff please",
                          "keep the nightly job, do not move invoices to a queue",
                          "and write down why we kept the nightly job"])

    def note(self):
        return (self.vault / "Projects" / "billing-api.md").read_text()

    def reindex(self):
        self.run_py("ksearch.py", args=["--reindex"])


