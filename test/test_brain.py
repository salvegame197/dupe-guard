    # ------------------------------------------------------------ search/recall

    def reindex(self):
        self.run_py("ksearch.py", args=["--reindex"])

    def test_default_vault_inside_a_hidden_folder_is_indexed(self):
        # Regression: the indexer skipped any path with a dot-folder ANYWHERE in
        # it, so a vault under, say, ~/.config or ~/.dupe-guard was never indexed.
        env = {**self.env, "DUPE_GUARD_VAULT": str(self.home / "vault")}
        shutil.copytree(self.vault, self.home / "vault")
        self.run_py("ksearch.py", env=env, args=["--reindex"])
        out = json.loads(self.run_py("ksearch.py", env=env, args=["backoff", "--json"]))
        self.assertTrue(any(r["title"] == "Exponential backoff" for r in out["results"]))

    def test_recall_speaks_on_a_subject_and_stays_quiet_otherwise(self):
        self.reindex()
        ctx = self.context(self.run_py("recall.py", {"prompt": "how should exponential backoff work for invoice retries",
                                                     "session_id": "r1"}))
        self.assertIsNotNone(ctx)
        self.assertIn("Exponential backoff", ctx)
        self.assertEqual(self.run_py("recall.py", {"prompt": "ok go ahead", "session_id": "r1"}), "")

    def test_a_small_fresh_vault_derives_no_stopwords(self):
        # Regression: with a handful of documents every word was in >25% of
        # them, became a stopword, and recall never spoke on a new vault.
        self.reindex()
        stop = json.loads((self.home / "brain" / "ksearch-stopwords.json").read_text())
        self.assertEqual(stop, [])

